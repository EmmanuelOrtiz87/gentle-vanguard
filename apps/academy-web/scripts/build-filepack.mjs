#!/usr/bin/env node
/**
 * build-filepack.mjs — snapshots referenced repo docs into data/files.js
 * so the Academy can open them offline (file:// cannot fetch).
 * Re-run whenever referenced documents change:  node scripts/build-filepack.mjs
 */
import { readFileSync, writeFileSync, existsSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '../../..');

const FILES = [
  'AGENTS.md',
  'QUICK-START.md',
  'README.md',
  'docs/stack-manual-full.md',
  'docs/reference/GLOSSARY.md',
  'docs/adr/ADR-0017-local-first-operating-model.md',
  'docs/adr/README.md',
  'docs/status/CANONICAL-STATUS.md',
  'docs/dashboard/DASHBOARD.md',
  'docs/security/DASHBOARD-ADMIN-STATUS.md',
  'docs/getting-started/README.md',
  'docs/guides/TESTING-GUIDE.md',
  'docs/guides/AUDIT-WORKFLOW.md',
  'docs/guides/OPERATION-GUIDE.md',
  'docs/guides/TROUBLESHOOTING-RUNBOOK.md',
  'docs/guides/FIRST-TIME-SETUP-CHECKLIST.md',
  'docs/reference/ARCHITECTURE.md',
  'docs/reference/SUBAGENT-ARCHITECTURE.md',
  'docs/reference/CONTEXT-EFFICIENCY-PROTOCOL.md',
  'docs/reference/CONTEXT-OPTIMIZATION-GUIDE.md',
  'docs/reference/REAL-TOKEN-TRACKING.md',
  'docs/reference/SKILL-ORGANIZATION.md',
  'docs/reference/PLUGIN-ARCHITECTURE.md',
  'rules/NORMATIVAS-ARCHITECTURE.md',
  'rules/NORMATIVAS-CODE-QUALITY.md',
  'rules/NORMATIVAS-OPS-DEVOPS.md',
  'rules/NORMATIVAS-WORKFLOW.md',
  'rules/NEXUS-NORMATIVA.md',
  'config/model-router.json',
  'config/token-budget-guard.json',
  'package.json',
  // Frequently cited source files (lessons reference them inline)
  'src/tokens/token-ingest.ts',
  'src/core/maintenance-watchtower.ts',
  'src/tools/event-sourcing.ts',
  'src/compression/structural-compression.ts',
  'src/response-cache.ts',
  'src/recommend-agent.ts',
  'src/route-and-delegate.ts',
  'src/agent-delegator.ts',
  'src/adaptive-steps.ts',
  'src/learning-engine.ts',
  'src/review/result-gatekeeper.ts',
  'src/review/review-lenses.ts',
  'src/generate-sbom.ts',
  'apps/web-dashboard/server/real-data.ts',
  'apps/web-dashboard/server/auth.ts',
  'apps/web-dashboard/server/rbac.ts',
  'apps/web-dashboard/server/dashboard-source-provenance.ts',
  'apps/web-dashboard/server/cache/tenant-lru-cache.ts',
  'config/review-lenses.json',
  'config/behavior-prompts.json',
  'config/dashboard-alerts.json',
  'config/auto-delegation.json',
  'config/subagent-mapping.json',
  'config/tenant-registry.json',
];

function jsString(s) {
  return JSON.stringify(s);
}

const entries = [];
for (const rel of FILES) {
  const abs = resolve(root, rel);
  if (!existsSync(abs)) { console.warn('SKIP (missing):', rel); continue; }
  let body = readFileSync(abs, 'utf8');
  if (body.length > 40000) body = body.slice(0, 40000) + '\n\n... (truncated for the offline pack — ver el archivo completo en el repo)';
  entries.push(`  ${jsString(rel)}: { title: ${jsString(rel.split('/').pop())}, lang: ${jsString(rel.endsWith('.json') ? 'json' : rel.match(/\.(ts|js|mjs)$/) ? 'code' : 'md')}, body: ${jsString(body)} }`);
}

const out = `/* Auto-generated by scripts/build-filepack.mjs — do not edit by hand.
   Offline snapshot of repo documents referenced from lessons ([[path]] chips). */
window.GV_FILES = {
${entries.join(',\n')}
};
`;
writeFileSync(resolve(here, '../data/files.js'), out, 'utf8');
console.log(`filepack: ${entries.length} files embedded`);
