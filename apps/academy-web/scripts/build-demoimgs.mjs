#!/usr/bin/env node
/**
 * build-demoimgs.mjs — embeds assets/demo/*.png as data URIs in data/demo-images.js
 * so the Demo gallery renders identically over file:// regardless of browser
 * subresource policies. Re-run after replacing screenshots.
 */
import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const here = dirname(fileURLToPath(import.meta.url));
const dir = resolve(here, '../assets/demo');
const out = ['/* Auto-generated by scripts/build-demoimgs.mjs — inline demo images. */', 'window.GV_IMG = {'];
for (const f of readdirSync(dir).filter(f => f.endsWith('.png'))) {
  const b64 = readFileSync(resolve(dir, f)).toString('base64');
  out.push(`  ${JSON.stringify(f.replace(/\.png$/, ''))}: 'data:image/png;base64,${b64}',`);
}
out.push('};');
writeFileSync(resolve(here, '../data/demo-images.js'), out.join('\n') + '\n', 'utf8');
console.log('demo images embedded:', out.length - 3);
