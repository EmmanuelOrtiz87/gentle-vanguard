param(
    [string]$Action = "pre-commit",
    [string]$Branch = "",
    [switch]$Quiet
)

$ErrorActionPreference = "Stop"

function Resolve-ProjectRoot {
    $dir = $PSScriptRoot
    for ($i = 0; $i -lt 8; $i++) {
        if (Test-Path (Join-Path $dir ".git")) { return $dir }
        $parent = Split-Path $dir -Parent
        if (-not $parent -or $parent -eq $dir) { break }
        $dir = $parent
    }
    return $PSScriptRoot
}

$ProjectRoot = Resolve-ProjectRoot
$DiagramScript = Join-Path $PSScriptRoot "codegraph-diagram.ps1"
$DiagramDir = Join-Path $ProjectRoot "docs\diagrams"
$DocsDir = Join-Path $ProjectRoot "docs"

function Get-PrBranch {
    if ($Branch) { return $Branch }
    try {
        $b = git -C $ProjectRoot rev-parse --abbrev-ref HEAD 2>$null
        if ($b) { return $b.Trim() }
    } catch { Write-Debug "Exception caught: param(
    [string]$Action = "pre-commit",
    [string]$Branch = "",
    [switch]$Quiet
)

