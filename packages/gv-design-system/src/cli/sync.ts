#!/usr/bin/env node
/**
 * Gentle-Vanguard Design System v2 — Sync CLI.
 *
 * Regenerates design tokens in all consuming apps.
 * Updates assets/tokens.v2.json (replacement for assets/tokens.json).
 * Writes tokens.css to each app's src/styles/ if applicable.
 *
 * Usage:
 *   npx tsx src/cli/sync.ts                # all apps
 *   npx tsx src/cli/sync.ts --app gv-analytics  # specific app
 *   npx tsx src/cli/sync.ts --dry-run      # show what would change
 */

import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { argv } from 'node:process';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
// src/cli/sync.ts -> packages/gv-design-system/
const DS_ROOT = join(__dirname, '..', '..');
// packages/gv-design-system/ -> repo root
const REPO_ROOT = resolve(DS_ROOT, '..', '..');
const TOKENS_JSON = join(DS_ROOT, 'src', 'tokens', 'tokens.json');
const APPS_DIR = join(REPO_ROOT, 'apps');

const args = argv.slice(2);
const dryRun = args.includes('--dry-run');
const appFlag = args.indexOf('--app');
const specificApp = appFlag >= 0 ? args[appFlag + 1] : null;

interface AppConsumer {
  name: string;
  path: string;
  consumesTokens: boolean;
}

function discoverConsumers(): AppConsumer[] {
  const consumers: AppConsumer[] = [
    { name: 'gv-analytics', path: join(APPS_DIR, 'gv-analytics'), consumesTokens: true },
    { name: 'web-dashboard', path: join(APPS_DIR, 'web-dashboard'), consumesTokens: true },
    { name: 'academy-web', path: join(APPS_DIR, 'academy-web'), consumesTokens: false },
    { name: 'content-cms', path: join(APPS_DIR, 'content-cms'), consumesTokens: false },
    { name: 'prompt-studio', path: join(APPS_DIR, 'prompt-studio'), consumesTokens: false },
    { name: 'archify', path: join(APPS_DIR, 'archify'), consumesTokens: false },
  ];
  return specificApp ? consumers.filter((c) => c.name === specificApp) : consumers;
}

function sync() {
  console.log('🔄 Gentle-Vanguard Design System v2 — Sync');
  console.log(`   Mode: ${dryRun ? 'DRY RUN' : 'APPLY'}`);
  console.log(`   Source: ${TOKENS_JSON}`);
  console.log('');

  if (!existsSync(TOKENS_JSON)) {
    console.error(`❌ Source tokens not found: ${TOKENS_JSON}`);
    process.exit(1);
  }

  const tokens = JSON.parse(readFileSync(TOKENS_JSON, 'utf-8'));
  console.log(`📦 Tokens version: ${tokens.version}`);
  console.log('');

  // 1. Generate legacy assets/tokens.v2.json (replacement for v1)
  const legacyTokensPath = join(REPO_ROOT, 'assets', 'tokens.v2.json');
  const legacyTokensContent = JSON.stringify(
    {
      version: tokens.version,
      description: 'Generated by @gentle-vanguard/design-system v2. Supersedes assets/tokens.json. See ADR-0026.',
      color: {
        primary: tokens.color.brand.cyan,
        primaryLight: tokens.color.brand.cyanSoft,
        primaryDark: tokens.color.brand.cyanDeep,
        accent: tokens.color.brand.purple,
        accentTeal: tokens.color.brand.purpleDeep,
        gold: tokens.color.brand.gold,
        background: tokens.color.surface.bg,
        backgroundElevated: tokens.color.surface.elevated,
        surface: tokens.color.surface.surface,
        surfaceIcon: tokens.color.surface.surfaceRaised,
        circuit: tokens.color.surface.bgDeep,
        glass: tokens.color.surface.glass,
        glassBorder: tokens.color.surface.glassBorder,
        textPrimary: tokens.color.text.primary,
        textSecondary: tokens.color.text.secondary,
        textBrand: tokens.color.brand.cyan,
        textMuted: tokens.color.text.muted,
        border: tokens.color.border.default,
        success: tokens.color.feedback.success,
        warning: tokens.color.feedback.warning,
        error: tokens.color.feedback.error,
      },
      typography: {
        displayFont: tokens.typography.fontFamily.display,
        bodyFont: tokens.typography.fontFamily.body,
        monoFont: tokens.typography.fontFamily.mono,
        monoAccentFont: tokens.typography.fontFamily.monoAccent,
      },
      cli: {
        titleColor: tokens.color.brand.cyan,
        successColor: tokens.color.feedback.success,
        errorColor: tokens.color.feedback.error,
        warningColor: tokens.color.feedback.warning,
        mutedColor: tokens.color.text.muted,
      },
    },
    null,
    2
  );

  if (dryRun) {
    console.log(`[DRY] Would write: ${legacyTokensPath}`);
  } else {
    writeFileSync(legacyTokensPath, legacyTokensContent);
    console.log(`✅ Wrote: ${legacyTokensPath}`);
  }

  // 2. Discover consuming apps
  const consumers = discoverConsumers();
  console.log('');
  console.log(`📋 Found ${consumers.length} consumer(s):`);
  for (const c of consumers) {
    const status = existsSync(c.path) ? '✓' : '✗ (missing)';
    console.log(`   ${status} ${c.name}`);
  }

  // 3. For each consumer, link the package if not already linked
  console.log('');
  console.log('🔗 Linking @gentle-vanguard/design-system to consumers...');
  for (const c of consumers) {
    if (!existsSync(c.path)) continue;
    if (dryRun) {
      console.log(`[DRY] Would link @gentle-vanguard/design-system to ${c.name}`);
      continue;
    }
    try {
      execSync('pnpm link ../../packages/gv-design-system', {
        cwd: c.path,
        stdio: 'pipe',
      });
      console.log(`✅ Linked: ${c.name}`);
    } catch (err) {
      const e = err as { stderr?: string; message?: string };
      console.log(`⚠️  ${c.name}: ${e.stderr || e.message || 'link failed (may already be linked)'}`);
    }
  }

  console.log('');
  console.log(dryRun ? '✅ DRY RUN complete.' : '✅ Sync complete.');
}

sync();
